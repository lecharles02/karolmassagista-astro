import fs from 'node:fs';
import path from 'node:path';
import { legacyRedirects } from '../config/redirects.mjs';

const rules = new Map();
for (const [source, destination] of legacyRedirects) {
  for (const variant of new Set([source, encodeURI(source)])) {
    rules.set(variant, destination);
    rules.set(`${variant}/`, destination);
  }
}

function walk(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(fullPath);
    else if (entry.name === 'index.astro') {
      const relative = path.relative('src/pages', directory).replaceAll('\\', '/');
      if (relative) rules.set(`/${relative}`, `/${relative}/`);
    }
  }
}
walk('src/pages');
const content = '# Generated by scripts/generate-redirects.mjs. Domain redirects run in Pages Functions.\n'
  + [...rules].map(([source, destination]) => `${source} ${destination} 301`).join('\n') + '\n';
fs.writeFileSync('public/_redirects', content);
console.log(`${rules.size} regras de redirecionamento geradas para Cloudflare Pages.`);
